/**
 * CSS Generator - Converts design tokens JSON to CSS
 * Run this to regenerate CSS from tokens
 */

import tokensData from '../base/tokens.json' with { type: 'json' }
import type { DesignTokens } from '../types'
import { generateThemeCSS, getResolvedTokens } from './parser'

const tokens = tokensData as DesignTokens

/**
 * Generate CSS file content from design tokens
 */
export function generateTokenCSS(): string {
  const { primitives, tailwindTheme, light, dark } = generateThemeCSS(tokens)

  return `/* =====================================================
   Design Tokens - Auto-generated from tokens.json
   DO NOT EDIT THIS FILE DIRECTLY
   Edit tokens.json and regenerate using npm run tokens
   ===================================================== */

@import "tailwindcss";

${tailwindTheme}
${primitives}
${light}
${dark}
`
}

/**
 * Get specific token value
 */
export function getToken(path: string, mode?: 'Light' | 'Dark'): string | undefined {
  const parts = path.split('.')
  const collection = parts[0] as 'primitives' | 'abstractions' | 'semantics'

  if (!['primitives', 'abstractions', 'semantics'].includes(collection)) {
    return
  }

  const resolved = getResolvedTokens(tokens, collection, mode)
  const tokenKey = parts.slice(1).join('-')

  return resolved[tokenKey]
}

/**
 * Apply tokens to document root (runtime)
 */
export function applyTokensToDOM(mode: 'Light' | 'Dark' = 'Light'): void {
  if (typeof window === 'undefined') {
    return
  }

  const root = document.documentElement

  // Apply primitives
  const primitives = getResolvedTokens(tokens, 'primitives')
  for (const [key, value] of Object.entries(primitives)) {
    root.style.setProperty(`--color-${key}`, value)
  }

  // Apply abstractions
  const abstractions = getResolvedTokens(tokens, 'abstractions')
  for (const [key, value] of Object.entries(abstractions)) {
    root.style.setProperty(`--color-${key}`, value)
  }

  // Apply semantic tokens
  const semantics = getResolvedTokens(tokens, 'semantics', mode)
  for (const [key, value] of Object.entries(semantics)) {
    root.style.setProperty(`--${key}`, value)
  }
}

// Export tokens data for use in other modules
export { tokens }
